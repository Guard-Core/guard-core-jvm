/**
 * Client IP resolution parity with the reference engine (guard-core Python,
 * `guard_core/_utils/ip_extraction.py` and `_utils/access_control.py`). The tables under
 * `src/test/resources` are generated by running the reference `extract_client_ip` and `_ip_in_list`
 * over each input, never hand-written.
 */
class ClientIpParityTest {
  private class StubResolver : RouteConfigResolverProtocol {
    override fun getRouteConfig(request: GuardRequest): Any? = null

    override fun shouldBypassCheck(checkName: String, routeConfig: Any?): Boolean = false

    override fun getCloudProvidersToCheck(routeConfig: Any?): List<String> = emptyList()
  }

  private fun table(name: String): JsonArray =
      Json.parseToJsonElement(
              javaClass.classLoader.getResourceAsStream(name)!!.readBytes().decodeToString(),
          )
          .jsonArray

  private fun JsonObject.text(key: String): String? =
      this[key].let { if (it == null || it is JsonNull) null else it.jsonPrimitive.content }

  private fun request(host: String?, xff: String?): TestRequest =
      TestRequest(
          clientHost = if (host.isNullOrEmpty()) null else host,
          headers = if (xff == null) emptyMap() else mapOf("X-Forwarded-For" to xff),
      )

  private suspend fun resolve(
      config: com.guardcore.config.SecurityConfig,
      request: TestRequest,
  ): GuardResponse? {
    val middleware = TestMiddleware(config, resolver = StubResolver())
    return RouteConfigCheck(middleware).check(request) ?: IpSecurityCheck(middleware).check(request)
  }

  @Test
  fun extractClientIpMatchesTheReference() {
    coreRunTest {
      val rows = table("client_ip_cases.json")
      assertTrue(rows.size >= 85, "at least 85 reference rows")
      for ((i, element) in rows.withIndex()) {
        val row = element.jsonObject
        val tp = row["tp"]!!.jsonArray.map { it.jsonPrimitive.content }
        val depth = row["depth"]!!.jsonPrimitive.int
        val label = "row $i host=${row.text("host")} xff=${row.text("xff")} tp=$tp depth=$depth"
        IpExtraction.resetOnceFlags()
        val config =
            try {
              coreTestConfig {
                trustedProxies = tp
                trustedProxyDepth = depth
              }
            } catch (e: com.guardcore.errors.ConfigValidationError) {
              continue
            }
        val req = request(row.text("host"), row.text("xff"))
        assertEquals(row.text("expected"), IpExtraction.extractClientIp(req, config), label)
      }
    }
  }

  @Test
  fun routeConfigCheckStoresTheReferenceIdentity() {
    coreRunTest {
      for ((i, element) in table("client_ip_cases.json").withIndex()) {
        val row = element.jsonObject
        val tp = row["tp"]!!.jsonArray.map { it.jsonPrimitive.content }
        val depth = row["depth"]!!.jsonPrimitive.int
        IpExtraction.resetOnceFlags()
        val config =
            try {
              coreTestConfig {
                trustedProxies = tp
                trustedProxyDepth = depth
              }
            } catch (e: com.guardcore.errors.ConfigValidationError) {
              continue
            }
        val req = request(row.text("host"), row.text("xff"))
        RouteConfigCheck(TestMiddleware(config, resolver = StubResolver())).check(req)
        assertEquals(row.text("expected"), req.state.getAttr("client_ip"), "row $i")
      }
    }
  }

  @Test
  fun ipListMatchingMatchesTheReference() {
    for ((i, element) in table("client_ip_lists.json").withIndex()) {
      val row = element.jsonObject
      val entries = row["entries"]!!.jsonArray.map { it.jsonPrimitive.content }
      val expected = row["expected"]!!.jsonPrimitive.boolean
      val canonical = row.text("canonical")!!
      assertEquals(
          expected,
          AccessControl.ipInList(parseAddress(canonical), canonical, entries),
          "row $i ip=$canonical entries=$entries",
      )
    }
  }

  @Test
  fun blacklistBlocksAnIpv4MappedClient() {
    coreRunTest {
      resetIpBanGlobalState()
      for (entry in listOf("127.0.0.1", "127.0.0.0/8", "::ffff:127.0.0.1")) {
        val config = coreTestConfig { blacklist = listOf(entry) }
        for (peer in listOf("127.0.0.1", "::ffff:127.0.0.1")) {
          val response = resolve(config, request(peer, null))
          assertEquals(403, response?.statusCode, "blacklist $entry peer $peer")
        }
        assertNull(resolve(config, request("::ffff:203.0.113.9", null)), "$entry spares others")
      }
    }
  }

  @Test
  fun whitelistAdmitsAnIpv4MappedClient() {
    coreRunTest {
      resetIpBanGlobalState()
      val config = coreTestConfig { whitelist = listOf("10.0.0.0/8") }
      assertNull(resolve(config, request("::ffff:10.1.1.1", null)))
      assertEquals(403, resolve(config, request("::ffff:203.0.113.9", null))?.statusCode)
    }
  }

  @Test
  fun forwardedIdentityFromATrustedProxyReachesTheIpCheck() {
    coreRunTest {
      resetIpBanGlobalState()
      val config = coreTestConfig {
        trustedProxies = listOf("127.0.0.1")
        blacklist = listOf("203.0.113.77")
      }
      val req = request("127.0.0.1", "::ffff:203.0.113.77")
      assertEquals(403, resolve(config, req)?.statusCode)
      assertEquals("203.0.113.77", req.state.getAttr("client_ip"))
    }
  }
}
