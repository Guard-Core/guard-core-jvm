/**
 * IP list precedence parity with the reference engine (guard-core Python,
 * `_utils/access_control.py` `_check_ip_lists_detail` and `core/checks/helpers.py`
 * `check_route_ip_access`): a configured whitelist decides alone and the blacklist is consulted
 * only when no whitelist is configured. `ip_list_precedence.json` is generated by running the
 * reference over every row, never hand-written.
 */
class IpListPrecedenceTest {
  private val rows =
      Json.parseToJsonElement(
              javaClass.classLoader
                  .getResourceAsStream("ip_list_precedence.json")!!
                  .readBytes()
                  .decodeToString(),
          )
          .jsonArray
          .map { it.jsonObject }

  private fun JsonObject.list(key: String): List<String> =
      this[key]!!.jsonArray.map { it.jsonPrimitive.content }

  private fun label(row: JsonObject) =
      "wl=${row.list("whitelist")} bl=${row.list("blacklist")} ip=${row["ip"]!!.jsonPrimitive.content}"

  @Test
  fun globalListsMatchTheReference() {
    coreRunTest {
      val failures = mutableListOf<String>()
      assertTrue(rows.size >= 120)
      for (row in rows) {
        val wl = row.list("whitelist")
        val bl = row.list("blacklist")
        // The reference treats an empty whitelist like an absent one.
        val whitelists: List<List<String>?> =
            if (wl.isEmpty()) listOf(null, emptyList()) else listOf(wl)
        for (whitelist in whitelists) {
          val config = coreTestConfig {
            this.whitelist = whitelist
            blacklist = bl
          }
          // The pipeline resolves the client identity canonically before any list check.
          val ip = IpExtraction.canonicalizeIp(row["ip"]!!.jsonPrimitive.content)
          val expected = row["global"]!!.jsonPrimitive.boolean
          val actual = AccessControl.checkIpAccess(ip, config).allowed
          if (expected != actual) {
            failures += "global ${label(row)} whitelist=$whitelist: expected $expected got $actual"
          }
        }
      }
      assertTrue(failures.isEmpty(), failures.joinToString("\n"))
    }
  }

  @Test
  fun routeListsMatchTheReference() {
    coreRunTest {
      val middleware = TestMiddleware(coreTestConfig())
      val failures = mutableListOf<String>()
      for (row in rows) {
        val ip = IpExtraction.canonicalizeIp(row["ip"]!!.jsonPrimitive.content)
        if (ip == "unknown") continue
        val wl = row.list("whitelist")
        val bl = row.list("blacklist")
        val route =
            RouteConfig().apply {
              ipWhitelist = wl.ifEmpty { null }
              ipBlacklist = bl.ifEmpty { null }
            }
        val expected = row["route"]!!.let { if (it is JsonNull) null else it.jsonPrimitive.boolean }
        val actual = ChecksHelpers.checkRouteIpAccess(ip, route, middleware)
        if (expected != actual) failures += "route ${label(row)}: expected $expected got $actual"
      }
      assertTrue(failures.isEmpty(), failures.joinToString("\n"))
    }
  }

  private class RouteResolver(private val route: RouteConfig) : RouteConfigResolverProtocol {
    override fun getRouteConfig(request: GuardRequest): Any? = route

    override fun shouldBypassCheck(checkName: String, routeConfig: Any?): Boolean = false

    override fun getCloudProvidersToCheck(routeConfig: Any?): List<String> = emptyList()
  }

  /** A configured route whitelist skips the global lists (the reference skip_ip_lists gate). */
  @Test
  fun routeAndGlobalListsMatchTheReference() {
    coreRunTest {
      resetIpBanGlobalState()
      val table =
          Json.parseToJsonElement(
                  javaClass.classLoader
                      .getResourceAsStream("ip_list_route_global.json")!!
                      .readBytes()
                      .decodeToString(),
              )
              .jsonArray
              .map { it.jsonObject }
      assertTrue(table.size >= 243)
      val failures = mutableListOf<String>()
      for (row in table) {
        val route =
            RouteConfig().apply {
              ipWhitelist = row.list("routeWhitelist").ifEmpty { null }
              ipBlacklist = row.list("routeBlacklist").ifEmpty { null }
            }
        val config = coreTestConfig {
          whitelist = row.list("globalWhitelist").ifEmpty { null }
          blacklist = row.list("globalBlacklist")
        }
        val request =
            TestRequest(clientHost = row["ip"]!!.jsonPrimitive.content, headers = emptyMap())
        val middleware = TestMiddleware(config, resolver = RouteResolver(route))
        val response =
            RouteConfigCheck(middleware).check(request)
                ?: IpSecurityCheck(middleware).check(request)
        val allowed = response == null
        val expected = row["allowed"]!!.jsonPrimitive.boolean
        if (allowed != expected) failures += "$row: expected $expected got $allowed"
      }
      assertTrue(failures.isEmpty(), failures.joinToString("\n"))
    }
  }
}
